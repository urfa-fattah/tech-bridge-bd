export class I18nService {
  static getLanguage() {
    return localStorage.getItem(LANG_STORAGE_KEY) || 'bn';
  }

  static t(key) {
    const lang = this.getLanguage();
    return TRANSLATIONS[lang]?.[key] || TRANSLATIONS['bn']?.[key] || key;
  }

  static setLanguage(lang) {
    const activeLang = lang === 'en' ? 'en' : 'bn';
    localStorage.setItem(LANG_STORAGE_KEY, activeLang);
    this.applyToDOM();
    window.dispatchEvent(new CustomEvent('techbridge-lang-changed', { detail: { lang: activeLang } }));
  }

  static toggleLanguage() {
    const current = this.getLanguage();
    const next = current === 'bn' ? 'en' : 'bn';
    this.setLanguage(next);
    return next;
  }

  /**
   * Translates the entire DOM between Bangla and English
   */
  static applyToDOM() {
    const lang = this.getLanguage();
    const isEn = lang === 'en';
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.bn;

    // 1. Explicit data-i18n attributes
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // 2. Explicit data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // 3. Deep DOM text walker: translate any text containing Bengali characters
    if (document.body) {
      const textWalker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        {
          acceptNode(node) {
            const parent = node.parentElement;
            if (!parent) return NodeFilter.FILTER_REJECT;
            const tag = parent.tagName.toLowerCase();
            if (tag === 'script' || tag === 'style' || tag === 'code' || tag === 'pre') {
              return NodeFilter.FILTER_REJECT;
            }
            if (node.nodeValue && node.nodeValue.trim().length > 0) {
              return NodeFilter.FILTER_ACCEPT;
            }
            return NodeFilter.FILTER_SKIP;
          }
        }
      );

      const nodesToProcess = [];
      while (textWalker.nextNode()) {
        nodesToProcess.push(textWalker.currentNode);
      }

      // Cache sorted phrases for high performance
      if (!this._sortedPhrases) {
        this._sortedPhrases = Object.keys(PHRASE_MAP).sort((a, b) => b.length - a.length);
      }

      nodesToProcess.forEach(node => {
        if (isEn) {
          const text = node.nodeValue;
          if (/[\u0980-\u09FF]/.test(text)) {
            if (!node._originalBnText) {
              node._originalBnText = text;
            }

            let translated = text;
            for (let i = 0; i < this._sortedPhrases.length; i++) {
              const phrase = this._sortedPhrases[i];
              if (translated.includes(phrase)) {
                translated = translated.split(phrase).join(PHRASE_MAP[phrase]);
              }
            }
            // Convert any remaining Bengali digits to standard English digits
            const bnDigits = ['০','১','২','৩','৪','৫','৬','৭','৮','৯'];
            for (let d = 0; d < 10; d++) {
              translated = translated.split(bnDigits[d]).join(d.toString());
            }
            node.nodeValue = translated;
          }
        } else {
          if (node._originalBnText) {
            node.nodeValue = node._originalBnText;
          }
        }
      });
    }

    // 4. Update Language Toggle labels in DOM
    document.querySelectorAll('.js-lang-label').forEach(el => {
      el.textContent = isEn ? 'বাংলা' : 'EN';
    });

    // 5. Update HTML lang attribute
    document.documentElement.setAttribute('lang', lang);
  }

  static init() {
    this.applyToDOM();

    // Event delegation for language toggle
    document.addEventListener('click', (e) => {
      const btn = e.target.closest('.js-lang-toggle');
      if (btn) {
        e.preventDefault();
        I18nService.toggleLanguage();
      }
    });
  }
}
